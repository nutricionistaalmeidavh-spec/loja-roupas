import {test,expect} from '@playwright/test';

test('categoria é carregada do servidor e carrinho volta após recarregar',async({page})=>{
 const sku='RESTORE-'+Math.random().toString(36).slice(2,10).toUpperCase();
 const name='Saia Restauro '+sku;
 await page.goto('/');
 await page.getByLabel('Usuário').fill('qa-admin');
 await page.getByLabel('Senha').fill('Senha-QA-Somente-CI-2026');
 await page.getByRole('button',{name:'Entrar na loja'}).click();
 await page.getByRole('button',{name:'Cadastrar produtos'}).click();
 await page.getByRole('button',{name:/Novo produto/}).click();
 const create=page.getByRole('dialog',{name:'Novo produto'});
 await create.getByLabel('Nome da peça').fill(name);
 await create.getByLabel('SKU',{exact:true}).fill(sku);
 await create.getByLabel('Cor',{exact:true}).fill('Vermelho');
 await create.getByLabel('Tamanho',{exact:true}).fill('M');
 await create.getByLabel('Preço (R$)').fill('74,90');
 await create.getByRole('button',{name:'Cadastrar produto',exact:true}).click();
 await expect(create.getByRole('status').filter({hasText:'Produto cadastrado'})).toBeVisible();
 await create.getByRole('button',{name:'Fechar Novo produto'}).click();
 await page.getByRole('button',{name:'Entrada de estoque'}).click();
 await page.getByRole('button',{name:'Entrada direta',exact:true}).click();
 const receiver=page.getByRole('dialog',{name:'Receber estoque'});
 await receiver.getByLabel('Localizar peça para recebimento (nome ou SKU)').fill(sku);
 const option=receiver.getByLabel('Variante (SKU)').locator('option',{hasText:sku});
 await expect(option).toBeAttached();
 await receiver.getByLabel('Variante (SKU)').selectOption((await option.getAttribute('value'))!);
 await receiver.getByLabel('Quantidade recebida').fill('2');
 await receiver.getByLabel('Justificativa obrigatória').fill('Entrada de estoque excepcional para validar a operação');
 await receiver.getByRole('button',{name:'Confirmar entrada direta'}).click();
 await expect(receiver.getByText(/Novo saldo em mãos: 2/)).toBeVisible();
 await receiver.getByRole('button',{name:'Fechar Receber estoque'}).click();
 await page.getByRole('button',{name:'Caixa',exact:true}).click();
 if(await page.getByRole('button',{name:'Abrir caixa',exact:true}).count()){
  await page.getByLabel('Valor inicial (R$)').fill('100,00');
  await page.getByRole('button',{name:'Abrir caixa',exact:true}).click();
 }
 await page.getByRole('button',{name:'PDV',exact:true}).click();
 await page.getByPlaceholder('Pesquisar produto, SKU ou código…').fill(sku);
 const card=page.locator('.product-card').filter({hasText:name});
 await expect(card).toBeVisible();
 await card.getByRole('button',{name:'Adicionar '+name}).click();
 await expect(page.getByText('1 peça adicionada')).toBeVisible();
 await page.reload();
 await page.getByLabel('Usuário').fill('qa-admin');
 await page.getByLabel('Senha').fill('Senha-QA-Somente-CI-2026');
 await page.getByRole('button',{name:'Entrar na loja'}).click();
 await expect(page.getByRole('button',{name:'Recuperar carrinho'})).toBeVisible();
 await page.reload();
 await page.getByLabel('Usuário').fill('qa-admin');
 await page.getByLabel('Senha').fill('Senha-QA-Somente-CI-2026');
 await page.getByRole('button',{name:'Entrar na loja'}).click();
 await page.getByRole('button',{name:'Recuperar carrinho'}).click();
 await expect(page.getByText('1 peça adicionada')).toBeVisible();
 await expect(page.getByText('R$ 74,90').first()).toBeVisible();
 await page.setViewportSize({width:390,height:844});
 await page.getByRole('button',{name:/Ver carrinho/}).click();
 const dialog=page.getByRole('dialog',{name:'Carrinho'});
 await expect(dialog).toBeFocused();
 await page.keyboard.press('Escape');
 await expect(dialog).toBeHidden();
 await expect(page.getByRole('button',{name:/Ver carrinho/})).toBeFocused();
});
