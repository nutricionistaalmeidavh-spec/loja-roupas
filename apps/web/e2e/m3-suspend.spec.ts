import {test,expect} from '@playwright/test';
test('M3: suspender e retomar venda sem lançar estoque nem pagamento',async({page})=>{
 const sku='DRAFT-'+Math.random().toString(36).slice(2,10).toUpperCase();
 const productName='Vestido Suspenso QA '+sku;
 await page.goto('/');
 await page.getByLabel('Usuário').fill('qa-admin');
 await page.getByLabel('Senha').fill('Senha-QA-Somente-CI-2026');
 await page.getByRole('button',{name:'Entrar na loja'}).click();
 await page.getByRole('button',{name:'Caixa',exact:true}).click();
 await expect(page.getByText('Consultando caixa no servidor…')).toBeHidden();
 if(await page.getByRole('button',{name:'Abrir caixa',exact:true}).count()){
  await page.getByLabel('Valor inicial (R$)').fill('0,00');
  await page.getByRole('button',{name:'Abrir caixa',exact:true}).click();
  await expect(page.getByText('Caixa aberto.')).toBeVisible();
 }else await expect(page.getByText('Caixa aberto',{exact:true})).toBeVisible();
 await page.getByRole('button',{name:'Cadastrar produtos'}).click();
 await page.getByLabel('Nome da peça').fill(productName);
 await page.getByLabel('SKU').fill(sku);
 await page.getByLabel('Cor').fill('Azul');
 await page.getByLabel('Tamanho').fill('M');
 await page.getByLabel('Preço (R$)').fill('80,00');
 await page.getByRole('button',{name:'Cadastrar produto',exact:true}).click();
 await expect(page.getByText(/Produto cadastrado:/)).toBeVisible();
 await page.getByRole('button',{name:'Entrada de estoque'}).click();
 await page.getByLabel('Localizar peça para recebimento (nome ou SKU)').fill(sku);
 const option=page.getByLabel('Variante (SKU)').locator('option',{hasText:sku});
 await expect(option).toBeAttached();
 await page.getByLabel('Variante (SKU)').selectOption((await option.getAttribute('value'))!);
 await page.getByLabel('Quantidade recebida').fill('2');
 await page.getByRole('button',{name:'Registrar entrada de estoque'}).click();
 await expect(page.getByText(/Novo saldo em mãos: 2/)).toBeVisible();
 await page.getByRole('button',{name:'PDV'}).click();
 await page.getByLabel('Buscar nome, SKU ou código').fill(sku);
 const card=page.locator('.product-card').filter({hasText:productName});
 await expect(card.getByText('2 disponíveis')).toBeVisible();
 await card.getByRole('button',{name:'Adicionar '+productName}).click();
 await expect(page.getByText('1 peça adicionada')).toBeVisible();
 await page.getByRole('button',{name:'Suspender venda'}).click();
 await expect(page.getByText(/Venda suspensa e salva no servidor/)).toBeVisible();
 await expect(page.getByText('0 peças adicionadas')).toBeVisible();
 await page.getByRole('button',{name:/Retomar venda · 1 itens/}).click();
 await expect(page.getByText('1 peça adicionada')).toBeVisible();
 await expect(card.getByText('2 disponíveis')).toBeVisible();
 await page.reload();
 await expect(page.getByRole('heading',{name:'Bem-vindo à sua loja'})).toBeVisible();
});
