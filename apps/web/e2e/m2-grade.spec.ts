import {test,expect} from '@playwright/test';
test('M2: ampliar grade existente e atualizar SKU, cor e tamanho',async({page})=>{
 const suffix=Math.random().toString(36).slice(2,10).toUpperCase();
 const sku='GRADE-'+suffix, second='GRG-'+suffix, updated='GRU-'+suffix;
 const name='Saia QA '+suffix;
 await page.goto('/');
 await page.getByLabel('Usuário').fill('qa-admin');
 await page.getByLabel('Senha').fill('Senha-QA-Somente-CI-2026');
 await page.getByRole('button',{name:'Entrar na loja'}).click();
 await page.getByRole('button',{name:'Cadastrar produtos'}).click();
 await page.getByLabel('Nome da peça').fill(name);
 await page.getByLabel('SKU').fill(sku);
 await page.getByLabel('Cor').fill('Bege');
 await page.getByLabel('Tamanho').fill('M');
 await page.getByLabel('Preço (R$)').fill('99,90');
 await page.getByRole('button',{name:'Cadastrar produto',exact:true}).click();
 await expect(page.getByText(/Produto cadastrado:/)).toBeVisible();
 await page.getByRole('combobox',{name:'Produto para editar'}).selectOption({label:name});
 await page.getByLabel('SKU novo').fill(second);
 await page.getByLabel('Cor nova').fill('Bege');
 await page.getByLabel('Tamanho novo').fill('G');
 await page.getByLabel('Preço novo (R$)').fill('109,90');
 await page.getByRole('button',{name:'Adicionar variante'}).click();
 await expect(page.getByText('Variante adicionada.')).toBeVisible();
 const opt=page.getByRole('combobox',{name:'Variante para preço'}).locator('option',{hasText:second});
 await expect(opt).toBeAttached();
 await page.getByRole('combobox',{name:'Variante para preço'}).selectOption((await opt.getAttribute('value'))!);
 await page.getByLabel('SKU existente').fill(updated);
 await page.getByLabel('Cor existente').fill('Areia');
 await page.getByLabel('Tamanho existente').fill('GG');
 await page.getByRole('button',{name:'Salvar atributos da variante'}).click();
 await expect(page.getByText('Atributos da variante atualizados.')).toBeVisible();
 await page.getByRole('button',{name:'PDV'}).click();
 await page.getByLabel('Buscar nome, SKU ou código').fill(updated);
 await expect(page.locator('.product-card').filter({hasText:name})).toBeVisible();
});
